// Satzland: the comma kingdom. Kommasetzung for Lotta, class 5 Gymnasium NRW (Kernlehrplan: Aufzählung,
// Haupt- und Nebensatzverknüpfung, Apposition, wörtliche Rede), following the verb-based method of
// Lindauer & Sutter ("Kommas und Könige"): the verb is the king, the words that belong to it are its people,
// together they form a kingdom; between two kingdoms stands a border post, the comma.
//
// Sentence format: the sentence with its correct commas, the kings in brackets.
//   [Wort]    a king (the verb), or the first part of one
//   [+Wort]   another part of the king before it (ruft … [+an], hat … [+gesehen], kommen [+kann])
//   [2:Wort]  a king with an explicit number, only needed for kingdoms inside kingdoms (Enklaven)
//   (,)       a comma the rules allow but do not require: both answers count as right
// Kingdoms, border types and explanations are derived from this; tests check every sentence.
// About a third of the sentences need no comma at all, so Lotta never learns "long sentence → comma".

